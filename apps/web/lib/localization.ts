const catalogs: Record<SupportedLocale, Record<MessageKey, MessageTemplate>> = {
  en: enCatalog,
  "zh-Hans": zhHansCatalog,
}

function normalizeLocale(value: string): string {
  return value.trim().replaceAll("_", "-").toLowerCase()
}

export function resolveSupportedLocale(
  requestedLocales: readonly string[]
): SupportedLocale {
  for (const requested of requestedLocales) {
    const locale = normalizeLocale(requested)
    if (locale === "zh" || locale.startsWith("zh-cn") || locale.startsWith("zh-sg") || locale.startsWith("zh-hans")) {
      return "zh-Hans"
    }
    if (locale === "en" || locale.startsWith("en-")) return "en"
  }
  return "en"
}

export function resolveLocalePreference(
  preference: LocalePreference,
  requestedLocales: readonly string[]
): SupportedLocale {
  return preference === "system"
    ? resolveSupportedLocale(requestedLocales)
    : preference
}

export function normalizeLocalePreference(
  value: string | null | undefined
): LocalePreference {
  return value === "en" || value === "zh-Hans" ? value : "system"
}

function interpolate(template: string, variables: MessageVariables): string {
  return template.replace(/\{\{([A-Za-z][A-Za-z0-9_]*)\}\}/g, (match, name: string) => {
    const value = variables[name]
    return value === undefined ? match : String(value)
  })
}

export function createTranslator(locale: SupportedLocale) {
  return (key: MessageKey, variables: MessageVariables = {}): string => {
    const template = catalogs[locale][key] ?? enCatalog[key]
    const value = typeof template === "function" ? template(variables) : template
    return interpolate(value, variables)
  }
}

export function translationKeys(): { en: MessageKey[]; zhHans: MessageKey[] } {
  return {
    en: Object.keys(enCatalog).sort() as MessageKey[],
    zhHans: Object.keys(zhHansCatalog).sort() as MessageKey[],
  }
}
